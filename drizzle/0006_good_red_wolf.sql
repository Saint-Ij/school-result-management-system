CREATE TYPE "public"."application_status" AS ENUM('pending', 'accepted', 'rejected');--> statement-breakpoint
CREATE TYPE "public"."gender" AS ENUM('male', 'female');--> statement-breakpoint
CREATE TYPE "public"."relationship" AS ENUM('father', 'mother', 'guardian', 'other');--> statement-breakpoint
CREATE TABLE "applications" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"first_name" varchar(100) NOT NULL,
	"last_name" varchar(100) NOT NULL,
	"middle_name" varchar(100),
	"gender" "gender" NOT NULL,
	"date_of_birth" date NOT NULL,
	"nationality" varchar(100) NOT NULL,
	"state_of_origin" varchar(100) NOT NULL,
	"local_government_area" varchar(100) NOT NULL,
	"parent_full_name" varchar(200) NOT NULL,
	"relationship" "relationship" NOT NULL,
	"occupation" varchar(150) NOT NULL,
	"email" varchar(255) NOT NULL,
	"phone_number" varchar(30) NOT NULL,
	"alternative_phone_number" varchar(30),
	"residential_address" text NOT NULL,
	"class_applying_for" varchar(50) NOT NULL,
	"program_type" varchar(50) NOT NULL,
	"previous_school_attended" varchar(255),
	"last_class_completed" varchar(100),
	"reason_for_transfer" text,
	"blood_group" varchar(10),
	"genotype" varchar(10),
	"medical_conditions" text,
	"disabilities" text,
	"passport_photograph_url" text NOT NULL,
	"birth_certificate_url" text NOT NULL,
	"report_card_url" text,
	"medical_certificate_url" text,
	"status" "application_status" DEFAULT 'pending' NOT NULL,
	"reviewed_by" uuid,
	"review_notes" text,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL
);
